import ClavimoCore

/// Human-readable names for Mac virtual key codes. Letter keys use their
/// US ANSI labels, which match the physical key positions that rules use.
enum KeyNames {
    static func name(for code: UInt16) -> String {
        names[code] ?? "Key \(code)"
    }

    /// Keys offered in pickers, grouped for menus.
    static let modifierKeys: [UInt16] = [0x37, 0x36, 0x3A, 0x3D, 0x3B, 0x3E, 0x38, 0x3C]
    static let commonKeys: [UInt16] = [0x35, 0x39, 0x30, 0x31, 0x24, 0x33, 0x75, 0x7B, 0x7C, 0x7D, 0x7E, 0x73, 0x77, 0x74, 0x79]
    static let functionKeys: [UInt16] = [0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F, 0x69, 0x6B, 0x71, 0x6A, 0x40, 0x4F, 0x50, 0x5A]
    static let letterAndDigitKeys: [UInt16] = [
        0x00, 0x0B, 0x08, 0x02, 0x0E, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2E,
        0x2D, 0x1F, 0x23, 0x0C, 0x0F, 0x01, 0x11, 0x20, 0x09, 0x0D, 0x07, 0x10, 0x06,
        0x1D, 0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19,
    ]

    private static let names: [UInt16: String] = [
        0x00: "A", 0x0B: "B", 0x08: "C", 0x02: "D", 0x0E: "E", 0x03: "F", 0x05: "G", 0x04: "H", 0x22: "I",
        0x26: "J", 0x28: "K", 0x25: "L", 0x2E: "M", 0x2D: "N", 0x1F: "O", 0x23: "P", 0x0C: "Q", 0x0F: "R",
        0x01: "S", 0x11: "T", 0x20: "U", 0x09: "V", 0x0D: "W", 0x07: "X", 0x10: "Y", 0x06: "Z",
        0x1D: "0", 0x12: "1", 0x13: "2", 0x14: "3", 0x15: "4", 0x17: "5", 0x16: "6", 0x1A: "7", 0x1C: "8", 0x19: "9",
        0x18: "=", 0x1B: "-", 0x1E: "]", 0x21: "[", 0x27: "'", 0x29: ";", 0x2A: "\\", 0x2B: ",", 0x2C: "/", 0x2F: ".",
        0x32: "`", 0x0A: "Section (ISO)",
        0x24: "Return", 0x30: "Tab", 0x31: "Space", 0x33: "Delete", 0x35: "Escape", 0x75: "Forward Delete",
        0x37: "Left Command", 0x36: "Right Command", 0x3A: "Left Option", 0x3D: "Right Option",
        0x3B: "Left Control", 0x3E: "Right Control", 0x38: "Left Shift", 0x3C: "Right Shift",
        0x39: "Caps Lock", 0x3F: "Fn",
        0x7B: "Left Arrow", 0x7C: "Right Arrow", 0x7D: "Down Arrow", 0x7E: "Up Arrow",
        0x73: "Home", 0x77: "End", 0x74: "Page Up", 0x79: "Page Down", 0x72: "Help",
        0x7A: "F1", 0x78: "F2", 0x63: "F3", 0x76: "F4", 0x60: "F5", 0x61: "F6", 0x62: "F7", 0x64: "F8",
        0x65: "F9", 0x6D: "F10", 0x67: "F11", 0x6F: "F12", 0x69: "F13", 0x6B: "F14", 0x71: "F15",
        0x6A: "F16", 0x40: "F17", 0x4F: "F18", 0x50: "F19", 0x5A: "F20",
    ]

    static func buttonName(_ number: Int) -> String {
        switch number {
        case 1: "Left Button"
        case 2: "Right Button"
        case 3: "Middle Button"
        case 4: "Button 4 (Back)"
        case 5: "Button 5 (Forward)"
        default: "Button \(number)"
        }
    }
}
